LOGO_CANDIDATES = ("logo.jpg", "logo.png", "logo.webp", "logo.svg")
AVATAR_CANDIDATES = ("community-avatar.png", "community-avatar.jpg", "community-avatar.webp")


def _brand_file_exists(filename):
    """Есть ли такой файл в папке фирменных изображений."""
    if not filename:
        return False
    # Защита: имя файла не должно выходить за пределы папки бренда
    if os.path.basename(filename) != filename:
        return False
    return os.path.isfile(os.path.join(LOGO_DIR, filename))


def find_logo_url():
    """
    Возвращает путь к логотипу (относительно static/), либо None.

    Сначала проверяем имя из настроек, потом — запасные варианты.
    """
    for name in LOGO_CANDIDATES:
        if _brand_file_exists(name):
            return "images/brand/" + name
    return None


def find_avatar_url():
    """Возвращает путь к аватару сообщества (относительно static/), либо None."""
    for name in AVATAR_CANDIDATES:
        if _brand_file_exists(name):
            return "images/brand/" + name
    return None


LOGO_URL = find_logo_url()
AVATAR_URL = find_avatar_url()

